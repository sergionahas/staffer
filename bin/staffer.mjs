#!/usr/bin/env node
// staffer init: sets up a PM workspace for one project.
//   1. copies the runtime (overview, watcher, spawn/close scripts) into the PM directory
//   2. writes staffer.config.json and worker-rules.md there (kept if they already exist)
//   3. installs the PM skill into ~/.claude/skills/<skill>/SKILL.md, filled in from the config
//   4. builds the cmux layout, when run from a cmux terminal
// Rerun it any time to upgrade the runtime or re-render the skill after editing staffer.config.json.
import { spawnSync } from "node:child_process";
import { chmodSync, copyFileSync, rmSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const MARK = "<!-- generated by staffer init; edit staffer.config.json and rerun init instead -->";

const HELP = `staffer: a project-manager Claude Code session that runs parallel worker sessions in cmux.

Usage:
  staffer init [options]

Run in a terminal, init lists the projects it finds (folders that are a git repo or hold
git repos, under each root) to pick with the arrow keys, then asks only what it can't detect.

Options (anything left out is asked for, or taken from an existing staffer.config.json):
  --workdir <path>     where the PM and workers start; skips the project picker  [picked, or cwd with --yes]
  --roots <a,b>        folders whose subfolders are listed as projects  [$STAFFER_ROOTS or ~]
  --dir <path>         where the PM tooling, config and state go          [<workdir>/.staffer]
  --project <name>     project name shown in the overview and the skill
  --repos <a/b,c/d>    GitHub repos whose open PRs the overview lists
  --prefix <ABC>       ticket prefix, e.g. ABC for ABC-123
  --tracker <text>     where tickets live, e.g. "Linear (the linear MCP server)"
  --owner <name>       what the PM calls you                                  [the user]
  --skill <name>       skill name, installed to ~/.claude/skills/<name>        [<project>-pm]
  --skills-dir <path>  install the skill somewhere else            [~/.claude/skills]
  --yes                don't ask; use flags, existing config and defaults
  --force              overwrite an existing SKILL.md not made by staffer
  --no-layout          don't build the cmux layout
  --new                build the layout in a new cmux workspace instead of this one
`;

function parseArgs(argv) {
  const o = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith("--")) { o._.push(a); continue; }
    const k = a.slice(2);
    if (["yes", "force", "no-layout", "new", "help"].includes(k)) o[k] = true;
    else o[k] = argv[++i];
  }
  return o;
}

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "project";
const expand = (p) => (p?.startsWith("~/") ? join(homedir(), p.slice(2)) : p);
const readJson = (p) => { try { return JSON.parse(readFileSync(p, "utf8")); } catch { return null; } };

function render(tpl, c) {
  const v = {
    project: c.project, dir: c.dir, skill: c.skill, owner: c.owner, workspaceName: c.workspaceName,
    prefix: c.ticketPrefix || "ABC", prefixLower: (c.ticketPrefix || "ABC").toLowerCase(),
    trackerParen: c.tracker ? ` (${c.tracker})` : "",
    trackerLine: c.tracker ? `Tickets live in ${c.tracker}.` : "",
  };
  return tpl.replace(/\{\{(\w+)\}\}/g, (m, k) => (k in v ? v[k] : m)).replace(/\n{3,}/g, "\n\n");
}

const skillsDirOf = (args) => resolve(expand(args["skills-dir"] ?? process.env.CLAUDE_SKILLS_DIR ?? join(homedir(), ".claude", "skills")));
// pm.config.json is the name used before the rename to staffer; read it if that's all there is.
const readConfig = (dir) => readJson(join(dir, "staffer.config.json")) ?? readJson(join(dir, "pm.config.json")) ?? {};
// True if the skill exists and staffer didn't write it (so init must not overwrite it).
const foreignSkill = (skillsDir, name) => {
  const f = join(skillsDir, name, "SKILL.md");
  return existsSync(f) && !/generated by (staffer|trafficcontrol|cmux-pm) init/.test(readFileSync(f, "utf8"));
};

// Flags, then existing config, then defaults. No prompts: used with --yes or without a terminal.
function answersFromFlags(args) {
  const workdir = resolve(expand(args.workdir ?? process.cwd()));
  const dir = resolve(expand(args.dir ?? join(workdir, ".staffer")));
  const prev = readConfig(dir);
  const pick = (flag, key, def) => args[flag] ?? (key in prev ? prev[key] : def);
  const project = pick("project", "project", "My project");
  const repos = args.repos ? args.repos.split(",").map((s) => s.trim()).filter(Boolean) : (prev.repos ?? []);
  return {
    workdir, dir, prev, project, repos,
    ticketPrefix: pick("prefix", "ticketPrefix", "").toUpperCase(),
    tracker: pick("tracker", "tracker", ""),
    owner: pick("owner", "owner", "the user"),
    skill: slug(pick("skill", "skill", `${slug(project)}-pm`)),
    layout: args["no-layout"] ? "none" : args.new ? "new" : "here",
  };
}

async function init(args) {
  const interactive = process.stdin.isTTY && process.stdout.isTTY && !args.yes;
  const a = interactive ? await (await import("../lib/interactive.mjs")).ask(args, { readConfig, foreignSkill, skillsDir: skillsDirOf(args), slug, expand })
    : answersFromFlags(args);
  const { workdir, dir, prev, project, repos, ticketPrefix, tracker, owner, skill } = a;

  const config = {
    workspaceName: "ADMIN", workerRules: "worker-rules.md",
    claudeArgs: ["--permission-mode", "bypassPermissions"],
    ...prev, project, workdir, repos, ticketPrefix, tracker, owner, skill,
  };

  // Check before writing anything
  const skillsDir = skillsDirOf(args);
  const skillFile = join(skillsDir, skill, "SKILL.md");
  if (foreignSkill(skillsDir, skill) && !args.force) {
    console.error(`✗ ${skillFile} exists and wasn't made by staffer. Pick another --skill, or pass --force.`);
    process.exit(1);
  }

  // 1. runtime
  mkdirSync(join(dir, "state"), { recursive: true });
  for (const f of readdirSync(join(ROOT, "src"))) {
    copyFileSync(join(ROOT, "src", f), join(dir, f));
    if (f.endsWith(".sh")) chmodSync(join(dir, f), 0o755);
  }
  copyFileSync(join(ROOT, "README.md"), join(dir, "README.md"));
  writeFileSync(join(dir, ".gitignore"), "state/\n.env\n.env.*\n*.log\n");

  // 2. config and rules
  writeFileSync(join(dir, "staffer.config.json"), JSON.stringify(config, null, 2) + "\n");
  rmSync(join(dir, "pm.config.json"), { force: true });
  const ctx = { ...config, dir };
  const rules = resolve(dir, config.workerRules);
  const newRules = !existsSync(rules);
  if (newRules) writeFileSync(rules, render(readFileSync(join(ROOT, "templates", "worker-rules.md"), "utf8"), ctx));
  writeFileSync(join(dir, "pm-prompt.md"), render(readFileSync(join(ROOT, "templates", "pm-prompt.md"), "utf8"), ctx));

  // 3. skill
  mkdirSync(dirname(skillFile), { recursive: true });
  writeFileSync(skillFile, render(readFileSync(join(ROOT, "templates", "SKILL.md"), "utf8"), ctx).trimEnd() + "\n\n" + MARK + "\n");

  console.log(`✓ PM tooling in ${dir}`);
  console.log(`✓ config: ${join(dir, "staffer.config.json")}`);
  console.log(`✓ worker rules: ${rules}${newRules ? " (new: edit the Repo rules section for your project)" : " (kept)"}`);
  console.log(`✓ skill: ${skillFile}`);

  // 4. layout
  if (a.layout === "none") return;
  if (!process.env.CMUX_WORKSPACE_ID) {
    console.log(`\nNext, from a cmux terminal: ${join(dir, "cmux.sh")} --new`);
    return;
  }
  const r = spawnSync(join(dir, "cmux.sh"), a.layout === "new" ? ["--new"] : [], { stdio: "inherit" });
  process.exit(r.status ?? 1);
}

const args = parseArgs(process.argv.slice(2));
const cmd = args._[0];
if (cmd === "init") await init(args);
else { process.stdout.write(HELP); process.exit(args.help || cmd === "help" || !cmd ? 0 : 2); }
